const generatedMarker = "<?php\n// Generated by Loom make:grpc. Do not edit.\n"

type grpcGeneratedFile struct {
	ImportPaths []string            `json:"import_paths"`
	ProtoFile   string              `json:"proto_file"`
	Routes      map[string][]string `json:"routes"`
}
type grpcManifest struct {
	Files map[string]grpcGeneratedFile `json:"files"`
}

func readGRPCManifest(root string) (grpcManifest, error) {
	manifest := grpcManifest{Files: map[string]grpcGeneratedFile{}}
	raw, err := os.ReadFile(filepath.Join(root, "config/grpc.generated.json"))
	if os.IsNotExist(err) {
		return manifest, nil
	}
	if err != nil {
		return manifest, err
	}
	if err := json.Unmarshal(raw, &manifest); err != nil {
		return manifest, fmt.Errorf("invalid generated gRPC manifest: %w", err)
	}
	if manifest.Files == nil {
		return manifest, fmt.Errorf("generated gRPC manifest requires files")
	}
	return manifest, nil
}

func withGeneratedGRPC(config *protocolConfig) (*protocolConfig, error) {
	manifest, err := readGRPCManifest(".")
	if err != nil {
		return nil, err
	}
	result := *config
	result.ImportPaths = append([]string{}, config.ImportPaths...)
	result.ProtoFiles = append([]string{}, config.ProtoFiles...)
	keys := make([]string, 0, len(manifest.Files))
	for key := range manifest.Files {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		file := manifest.Files[key]
		for _, root := range file.ImportPaths {
			result.ImportPaths = appendUnique(result.ImportPaths, root)
		}
		result.ProtoFiles = appendUnique(result.ProtoFiles, file.ProtoFile)
	}
	return &result, nil
}

func appendUnique(values []string, value string) []string {
	for _, v := range values {
		if v == value {
			return values
		}
	}
	return append(values, value)
}

var phpIdentifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

func phpName(value string) (string, error) {
	reserved := " abstract and array as break callable case catch class clone const continue declare default die do echo else elseif empty enddeclare endfor endforeach endif endswitch endwhile enum eval exit extends final finally fn for foreach function global goto if implements include include_once instanceof insteadof interface isset list match namespace new or print private protected public readonly require require_once return static switch throw trait try unset use var while xor yield int float bool string void null true false mixed never self parent object resource numeric "
	if !phpIdentifier.MatchString(value) || strings.Contains(reserved, " "+strings.ToLower(value)+" ") || strings.HasPrefix(value, "__") {
		return "", fmt.Errorf("unsupported PHP identifier: %s", value)
	}
	return strings.ToUpper(value[:1]) + value[1:], nil
}

// checkedPath refuses traversal and symlink ancestors before writing artifacts.
func checkedPath(root, relative string) (string, error) {
	root, err := filepath.Abs(root)
	if err != nil {
		return "", err
	}
	target := filepath.Join(root, filepath.FromSlash(relative))
	rel, err := filepath.Rel(root, target)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) || filepath.IsAbs(rel) {
		return "", fmt.Errorf("path escapes project: %s", relative)
	}
	current := root
	for _, part := range strings.Split(rel, string(filepath.Separator)) {
		current = filepath.Join(current, part)
		info, err := os.Lstat(current)
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return "", err
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return "", fmt.Errorf("refusing symlink path: %s", current)
		}
	}
	return target, nil
}

func writeGenerated(path string, content []byte) error {
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	file, err := os.CreateTemp(filepath.Dir(path), ".grpc-*")
	if err != nil {
		return err
	}
	name := file.Name()
	defer os.Remove(name)
	if _, err := file.Write(content); err != nil {
		file.Close()
		return err
	}
	if err := file.Close(); err != nil {
		return err
	}
	return os.Rename(name, path)
}

func generateGRPC(ctx context.Context, root, input string, config *protocolConfig, out io.Writer) error {
	if config == nil {
		return fmt.Errorf("enable grpc in config/loom.json before generating services")
	}
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	if filepath.IsAbs(input) {
		relative, e := filepath.Rel(root, input)
		if e != nil {
			return e
		}
		input = relative
	}
	source, err := checkedPath(root, input)
	if err != nil {
		return err
	}
	if filepath.Ext(source) != ".proto" {
		return fmt.Errorf("expected a .proto file")
	}
	if _, err := os.Stat(source); err != nil {
		return err
	}
	imports := append([]string{}, config.ImportPaths...)
	var entry string
	for _, dir := range imports {
		base := dir
		if !filepath.IsAbs(base) {
			base = filepath.Join(root, base)
		}
		rel, e := filepath.Rel(base, source)
		if e == nil && rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
			entry = filepath.ToSlash(rel)
			break
		}
	}
	if entry == "" {
		rel, _ := filepath.Rel(root, filepath.Dir(source))
		imports = append(imports, filepath.ToSlash(rel))
		entry = filepath.Base(source)
	}
	// A same-named file in an earlier import root must not silently replace input.
	expected, err := os.Stat(source)
	if err != nil {
		return err
	}
	for _, dir := range imports {
		base := dir
		if !filepath.IsAbs(base) {
			base = filepath.Join(root, base)
		}
		actual, e := os.Stat(filepath.Join(base, filepath.FromSlash(entry)))
		if e == nil {
			if !os.SameFile(expected, actual) {
				return fmt.Errorf("ambiguous proto import %s; choose a unique path beneath an import root", entry)
			}
			break
		}
	}
	resolved := make([]string, 0, len(imports))
	for _, dir := range imports {
		if filepath.IsAbs(dir) {
			resolved = append(resolved, dir)
		} else {
			resolved = append(resolved, filepath.Join(root, dir))
		}
	}
	schema, err := protocol.Load(ctx, resolved, []string{entry})
	if err != nil {
		return err
	}
	manifest, err := readGRPCManifest(root)
	if err != nil {
		return err
	}
	rel, _ := filepath.Rel(root, source)
	key := filepath.ToSlash(rel)
	record := grpcGeneratedFile{ImportPaths: imports, ProtoFile: entry, Routes: map[string][]string{}}
	type artifact struct {
		path, content string
		business      bool
	}
	var artifacts []artifact
	for _, service := range schema.Services {
		parts := strings.Split(string(service.FullName()), ".")
		for i, part := range parts {
			name, e := phpName(part)
			if e != nil {
				return e
			}
			parts[i] = name
		}
		name := parts[len(parts)-1]
		packagePath := strings.Join(parts[:len(parts)-1], "/")
		suffix := strings.Join(parts[:len(parts)-1], "\\")
		if suffix != "" {
			suffix = "\\" + suffix
		}
		namespace := "App\\Grpc\\Services" + suffix
		baseNamespace := "App\\Grpc\\Generated" + suffix
		class := namespace + "\\" + name
		base := generatedMarker + "declare(strict_types=1);\n\nnamespace " + baseNamespace + ";\n\nabstract class " + name + "Base\n{\n"
		methods := map[string]bool{}
		var stubs string
		for i := 0; i < service.Methods().Len(); i++ {
			method := service.Methods().Get(i)
			methodName := string(method.Name())
			if _, err := phpName(methodName); err != nil {
				return err
			}
			methodName = strings.ToLower(methodName[:1]) + methodName[1:]
			if methods[strings.ToLower(methodName)] {
				return fmt.Errorf("PHP method name collision: %s", method.FullName())
			}
			methods[strings.ToLower(methodName)] = true
			record.Routes["/"+string(service.FullName())+"/"+string(method.Name())] = []string{class, methodName}
			inputType := "array"
			switch string(method.Input().FullName()) {
			case "google.protobuf.StringValue", "google.protobuf.BytesValue", "google.protobuf.Timestamp", "google.protobuf.Duration", "google.protobuf.FieldMask", "google.protobuf.Int64Value", "google.protobuf.UInt64Value":
				inputType = "string"
			case "google.protobuf.Int32Value", "google.protobuf.UInt32Value":
				inputType = "int"
			case "google.protobuf.BoolValue":
				inputType = "bool"
			case "google.protobuf.Value", "google.protobuf.DoubleValue", "google.protobuf.FloatValue":
				inputType = "mixed"
			}
			stubs += "    /** Request: " + string(method.Input().FullName()) + "; response: " + string(method.Output().FullName()) + " */\n    public function " + methodName + "(" + inputType + " $request)\n    {\n        throw new \\Loom\\Grpc\\RpcException('unimplemented', 'Implement " + methodName + " in " + name + "');\n    }\n\n"
		}
		base += stubs + "}\n"
		artifacts = append(artifacts, artifact{path: filepath.ToSlash(filepath.Join("app/Grpc/Generated", packagePath, name+"Base.php")), content: base})
		business := "<?php\ndeclare(strict_types=1);\n\nnamespace " + namespace + ";\n\n// This business file is never overwritten by make:grpc.\nfinal class " + name + " extends \\" + baseNamespace + "\\" + name + "Base\n{\n" + stubs + "}\n"
		artifacts = append(artifacts, artifact{path: filepath.ToSlash(filepath.Join("app/Grpc/Services", packagePath, name+".php")), content: business, business: true})
	}
	for otherKey, other := range manifest.Files {
		if otherKey == key {
			continue
		}
		for _, target := range other.Routes {
			for _, candidate := range record.Routes {
				if len(target) < 2 {
					return fmt.Errorf("invalid generated route in %s", otherKey)
				}
				if strings.EqualFold(target[0], candidate[0]) {
					return fmt.Errorf("generated PHP class already owned by %s: %s", otherKey, candidate[0])
				}
			}
		}
	}
	manifest.Files[key] = record
	// Validate the combined contract before modifying any files (including conflicts).
	allRoots, allFiles := append([]string{}, config.ImportPaths...), append([]string{}, config.ProtoFiles...)
	for _, file := range manifest.Files {
		for _, dir := range file.ImportPaths {
			allRoots = appendUnique(allRoots, dir)
		}
		allFiles = appendUnique(allFiles, file.ProtoFile)
	}
	for i, dir := range allRoots {
		if !filepath.IsAbs(dir) {
			allRoots[i] = filepath.Join(root, dir)
		}
	}
	if _, err := protocol.Load(ctx, allRoots, allFiles); err != nil {
		return err
	}
	seenPaths := map[string]bool{}
	for _, a := range artifacts {
		target, e := checkedPath(root, a.path)
		if e != nil {
			return e
		}
		lower := strings.ToLower(target)
		if seenPaths[lower] {
			return fmt.Errorf("generated path collision: %s", a.path)
		}
		seenPaths[lower] = true
		old, e := os.ReadFile(target)
		if e != nil && !os.IsNotExist(e) {
			return e
		}
		if e == nil && !a.business && !strings.HasPrefix(string(old), generatedMarker) {
			return fmt.Errorf("refusing to overwrite non-generated file: %s", a.path)
		}
	}
	manifestPath, err := checkedPath(root, "config/grpc.generated.json")
	if err != nil {
		return err
	}
	for _, a := range artifacts {
		target, _ := checkedPath(root, a.path)
		if a.business {
			if err := os.MkdirAll(filepath.Dir(target), 0755); err != nil {
				return err
			}
			f, e := os.OpenFile(target, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0644)
			if os.IsExist(e) {
				fmt.Fprintln(out, "保留", a.path)
				continue
			}
			if e != nil {
				return e
			}
			_, e = io.WriteString(f, a.content)
			closeErr := f.Close()
			if e != nil {
				return e
			}
			if closeErr != nil {
				return closeErr
			}
		} else if err := writeGenerated(target, []byte(a.content)); err != nil {
			return err
		}
		fmt.Fprintln(out, "生成", a.path)
	}
	raw, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		return err
	}
	if err := writeGenerated(manifestPath, append(raw, '\n')); err != nil {
		return err
	}
	fmt.Fprintln(out, "已更新 config/grpc.generated.json；填写业务类后重启宿主。")
	return nil
}

func runMakeGRPC(ctx context.Context, config *protocolConfig, args []string, out, errOut io.Writer) int {
	if len(args) == 1 && (args[0] == "--help" || args[0] == "-h") {
		fmt.Fprintln(out, "用法：loom make:grpc proto/user.proto\n生成 PHP 业务类、可再生基类及注册清单；已有业务文件始终保留。")
		return 0
	}
	if len(args) != 1 {
		fmt.Fprintln(errOut, "用法：loom make:grpc proto/user.proto")
		return 2
	}
	if err := generateGRPC(ctx, ".", args[0], config, out); err != nil {
		fmt.Fprintln(errOut, err)
		return 1
	}
	return 0
}
