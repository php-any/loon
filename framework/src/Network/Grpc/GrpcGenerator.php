<?php

declare(strict_types=1);

namespace Loom;

/**
 * 从项目内 proto 构造生成计划并生成 PHP 基类、业务骨架及清单，保护手写业务文件且拒绝路径越界。
 *
 * 构造参数：
 * - $config（\Loom\Config）：项目配置实例，提供配置读取及项目路径解析。
 *
 * 返回值：使用 new 构造时得到 GrpcGenerator 实例；注册到容器时由容器管理实例的创建与复用。
 *
 * 使用示例（依赖对象由所在应用或测试环境提供）：
 * @example $generator->generate('proto/release.proto', true);
 */
final class GrpcGenerator
{
    private \Loom\Config $config;

    /**
     * 初始化 GrpcGenerator 实例及其依赖。从项目内 proto 构造生成计划并生成 PHP 基类、业务骨架及清单，保护手写业务文件且拒绝路径越界。
     *
     * @param \Loom\Config $config 项目配置实例，提供配置读取及项目路径解析。
     * @return void 无直接返回值；通过 new 表达式取得初始化后的实例。
     *
     * 使用示例（依赖对象由所在应用或测试环境提供）：
     * @example $generator->generate('proto/release.proto', true);
     */
    public function __construct(\Loom\Config $config)
    {
        $this->config = $config;
    }

    private const MARKER = "<?php\n// Generated by Loom make:grpc. Do not edit.\n";
    /**
     * 解析协议并校验导入歧义、命名冲突及现有文件归属，构建待写入内容但不写磁盘。
     *
     * @param string $input 项目内已存在的 .proto 文件路径，相对项目根目录或绝对路径。
     * @return array 含 key、record、manifest、artifacts、services 的生成计划。
     *
     * 使用示例（依赖对象由所在应用或测试环境提供）：
     * @example $plan = $generator->plan('proto/release.proto');
     */
    public function plan(string $input): array
    {
        $root = str_replace('\\', '/', realpath($this->config->root()));
        $source = realpath($this->config->path($input));
        if ($source === false || !is_file($source) || pathinfo($source, PATHINFO_EXTENSION) !== 'proto') {
            throw new \InvalidArgumentException('Expected an existing .proto file');
        }
        $source = str_replace('\\', '/', $source);
        if (!str_starts_with($source, $root . '/')) {
            throw new \InvalidArgumentException('Proto must be inside this project');
        }
        $key = substr($source, strlen($root) + 1);
        $config = $this->config->get('grpc');
        $imports = $config['import_paths'];
        $entry = null;
        foreach ($imports as $path) {
            $base = realpath($this->config->path($path));
            if ($base !== false) {
                $base = str_replace('\\', '/', $base);
                if (str_starts_with($source, $base . '/')) {
                    $entry = substr($source, strlen($base) + 1);
                    break;
                }
            }
        }
        if ($entry === null) {
            $imports[] = dirname($key);
            $entry = basename($key);
        }
        $paths = [];
        foreach ($imports as $path) {
            $paths[] = $this->config->path($path);
            $candidate = realpath($this->config->path($path) . '/' . $entry);
            if ($candidate !== false && str_replace('\\', '/', $candidate) !== $source) {
                throw new \InvalidArgumentException('Ambiguous proto import: ' . $entry);
            }
        }
        $schema = new \Net\Grpc\Schema([$entry], $paths);
        $groups = [];
        foreach (json_decode($schema->methodsJson(), true, 512, JSON_THROW_ON_ERROR) as $method) {
            if ($method['clientStreaming'] || $method['serverStreaming']) {
                throw new \InvalidArgumentException($key . ': streaming RPC is unsupported: ' . $method['path']);
            }
            $groups[$method['service']][] = $method;
        }
        $manifestPath = $this->target('generated/grpc/routes.json');
        $manifest = is_file($manifestPath) ? json_decode(file_get_contents($manifestPath), true, 512, JSON_THROW_ON_ERROR) : ['files' => []];
        $record = ['import_paths' => $imports, 'proto_file' => $entry, 'routes' => []];
        $artifacts = [];
        $owned = [];
        $services = [];
        foreach ($groups as $service => $methods) {
            $serviceName = $service;
            $prefix = $config['package_prefix'] ?? '';
            if ($prefix !== '' && str_starts_with($serviceName, $prefix . '.')) {
                $serviceName = substr($serviceName, strlen($prefix) + 1);
            }
            $parts = [];
            foreach (explode('.', $serviceName) as $part) {
                $parts[] = self::identifier($part);
            }
            $name = array_pop($parts);
            $suffix = $parts === [] ? '' : '\\' . implode('\\', $parts);
            $namespace = 'App\\Grpc\\Services' . $suffix;
            $baseNamespace = 'Generated\\Grpc' . $suffix;
            $class = $namespace . '\\' . $name;
            if (isset($owned[strtolower($class)])) {
                throw new \InvalidArgumentException('PHP class name collision');
            }
            $owned[strtolower($class)] = true;
            $names = [];
            $stubs = '';
            foreach ($methods as $method) {
                $action = lcfirst(self::identifier($method['method']));
                if (isset($names[strtolower($action)])) {
                    throw new \InvalidArgumentException('PHP method name collision');
                }
                $names[strtolower($action)] = $action;
                $record['routes'][$method['path']] = [$class, $action];
                $types = ['StringValue' => 'string', 'BytesValue' => 'string', 'Timestamp' => 'string', 'Duration' => 'string', 'FieldMask' => 'string', 'Int64Value' => 'string', 'UInt64Value' => 'string', 'Int32Value' => 'int', 'UInt32Value' => 'int', 'BoolValue' => 'bool', 'Value' => 'mixed', 'DoubleValue' => 'mixed', 'FloatValue' => 'mixed'];
                $type = str_starts_with($method['input'], 'google.protobuf.') ? ($types[substr($method['input'], 16)] ?? 'array') : 'array';
                $stubs .= '    public function ' . $action . '(' . $type . ' $request)' . "\n    {\n" . '        throw new \\Loom\\Grpc\\RpcException(\'unimplemented\', \'Implement ' . $action . ' in ' . $name . '\');' . "\n    }\n\n";
            }
            $dir = $parts === [] ? '' : implode('/', $parts) . '/';
            $services[] = ['class' => $class, 'path' => 'app/Grpc/Services/' . $dir . $name . '.php', 'methods' => array_values($names)];
            $artifacts[] = ['path' => 'generated/grpc/' . $dir . $name . 'Base.php', 'business' => false, 'content' => self::MARKER . "declare(strict_types=1);\n\nnamespace " . $baseNamespace . ";\n\nabstract class " . $name . "Base\n{\n" . $stubs . "}\n"];
            $artifacts[] = ['path' => 'app/Grpc/Services/' . $dir . $name . '.php', 'business' => true, 'content' => "<?php\ndeclare(strict_types=1);\n\nnamespace " . $namespace . ";\n\n// This business file is never overwritten by make:grpc.\nfinal class " . $name . ' extends \\' . $baseNamespace . '\\' . $name . "Base\n{\n" . $stubs . "}\n"];
        }
        foreach ($manifest['files'] as $otherKey => $other) {
            if ($otherKey === $key) {
                continue;
            }
            foreach ($other['routes'] as $target) {
                if (isset($owned[strtolower($target[0])])) {
                    throw new \InvalidArgumentException('Generated class already owned by ' . $otherKey);
                }
            }
        }
        $manifest['files'][$key] = $record;
        $allFiles = $config['proto_files'];
        $allPaths = $config['import_paths'];
        foreach ($manifest['files'] as $file) {
            $allFiles[] = $file['proto_file'];
            $allPaths = array_merge($allPaths, $file['import_paths']);
        }
        $absolute = [];
        foreach (array_unique($allPaths) as $path) {
            $absolute[] = $this->config->path($path);
        }
        new \Net\Grpc\Schema(array_values(array_unique($allFiles)), $absolute);
        foreach ($artifacts as $artifact) {
            $target = $this->target($artifact['path']);
            if (is_file($target) && !$artifact['business'] && !str_starts_with(str_replace("\r\n", "\n", file_get_contents($target)), self::MARKER)) {
                throw new \RuntimeException('Refusing to overwrite non-generated file: ' . $target);
            }
        }
        return ['key' => $key, 'record' => $record, 'manifest' => $manifest, 'artifacts' => $artifacts, 'services' => $services];
    }
    /**
     * 输出生成动作及实现诊断，非预览模式才写基类和清单；已存在业务文件保留。
     *
     * @param string $input 项目内已存在的 .proto 文件路径，相对项目根目录或绝对路径。
     * @param bool $dryRun true 仅预览，false 执行实际写入。默认值为 false。
     * @return void 无返回值；dryRun=true 时仅打印计划。
     *
     * 使用示例（依赖对象由所在应用或测试环境提供）：
     * @example $generator->generate('proto/release.proto', true);
     */
    public function generate(string $input, bool $dryRun = false): void
    {
        $plan = $this->plan($input);
        foreach ($plan['artifacts'] as $artifact) {
            $target = $this->target($artifact['path']);
            $exists = file_exists($target);
            $action = $exists ? ($artifact['business'] ? 'KEEP' : 'UPDATE') : 'CREATE';
            echo $action . ' ' . $artifact['path'] . "\n";
        }
        echo (is_file($this->config->path('generated/grpc/routes.json')) ? 'UPDATE' : 'CREATE') . " generated/grpc/routes.json\n";
        $this->reportImplementations($plan['services']);
        if ($dryRun) {
            echo "Preview only: no files written\n";
            return;
        }
        foreach ($plan['artifacts'] as $artifact) {
            $target = $this->target($artifact['path']);
            if ($artifact['business'] && file_exists($target)) {
                continue;
            }
            if (!is_dir(dirname($target)) && !mkdir(dirname($target), 0755, true)) {
                throw new \RuntimeException('Cannot create generated directory');
            }
            if ($artifact['business']) {
                $file = fopen($target, 'x');
                if ($file === false) {
                    throw new \RuntimeException('Cannot exclusively create business source');
                }
                try {
                    if (fwrite($file, $artifact['content']) !== strlen($artifact['content'])) {
                        throw new \RuntimeException('Incomplete generated source');
                    }
                } finally {
                    fclose($file);
                }
            } else {
                self::write($target, $artifact['content']);
            }
        }
        $manifestPath = $this->target('generated/grpc/routes.json');
        if (!is_dir(dirname($manifestPath)) && !mkdir(dirname($manifestPath), 0755, true)) {
            throw new \RuntimeException('Cannot create generated directory');
        }
        self::write($manifestPath, json_encode($plan['manifest'], JSON_THROW_ON_ERROR | JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n");
        echo 'Generated gRPC services: ' . $plan['key'] . "\n";
    }
    /**
     * 检查业务文件直接方法声明，输出缺失方法或 unimplemented 占位提示。
     *
     * @param array $services 生成计划中的服务列表，每项包含 class、path、methods。
     * @return void 无返回值，诊断写入标准输出。
     *
     * 内部调用示例（仅类内使用）：
     * @example $this->reportImplementations($plan['services']);
     */
    private function reportImplementations(array $services): void
    {
        foreach ($services as $service) {
            $path = $this->config->path($service['path']);
            $methods = is_file($path) ? GrpcSource::methods(file_get_contents($path), $service['class']) : [];
            foreach ($service['methods'] as $method) {
                $lookup = strtolower($method);
                if (!isset($methods[$lookup])) {
                    echo 'TODO ' . $service['class'] . '::' . $method . ' — 未声明实现，请补充方法或确认继承/trait 实现' . "\n";
                } elseif (str_contains($methods[$lookup], 'RpcException') && (str_contains($methods[$lookup], "'unimplemented'") || str_contains($methods[$lookup], '"unimplemented"'))) {
                    echo 'TODO ' . $service['class'] . '::' . $method . ' — 包含 unimplemented 占位，请确认实现' . "\n";
                }
            }
        }
    }
    /**
     * 验证可映射为 PHP 标识符的协议名称，拒绝保留字及双下划线前缀，首字母转大写。
     *
     * @param string $value 准备映射为 PHP 类名或方法名的协议标识符。
     * @return string 规范化的 PHP 标识符。
     *
     * 使用示例（依赖对象由所在应用或测试环境提供）：
     * @example $name = GrpcGenerator::identifier('invoice');
     */
    public static function identifier(string $value): string
    {
        $reserved = ' abstract and array as break callable case catch class clone const continue declare default die do echo else elseif empty enddeclare endfor endforeach endif endswitch endwhile enum eval exit extends final finally fn for foreach function global goto if implements include include_once instanceof insteadof interface isset list match namespace new or print private protected public readonly require require_once return static switch throw trait try unset use var while xor yield int float bool string void null true false mixed never self parent object resource numeric ';
        if (!preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $value) || str_starts_with($value, '__') || str_contains($reserved, ' ' . strtolower($value) . ' ')) {
            throw new \InvalidArgumentException('Unsupported PHP identifier: ' . $value);
        }
        return ucfirst($value);
    }
    /**
     * 将安全相对产物路径定位到项目目录，拒绝上级路径、驱动符号和符号链接。
     *
     * @param string $relative 项目内产物相对路径，使用 / 分隔，不允许空段、.. 或符号链接。
     * @return string 项目内目标路径，不要求目标文件已经存在。
     *
     * 使用示例（依赖对象由所在应用或测试环境提供）：
     * @example $path = $generator->target('generated/grpc/InvoiceBase.php');
     */
    public function target(string $relative): string
    {
        $target = $this->config->root();
        foreach (explode('/', $relative) as $part) {
            if ($part === '' || $part === '.' || $part === '..' || str_contains($part, '\\') || str_contains($part, ':')) {
                throw new \InvalidArgumentException('Invalid artifact path');
            }
            $target .= '/' . $part;
            if (is_link($target)) {
                throw new \RuntimeException('Refusing symlink artifact path');
            }
        }
        return $target;
    }
    /**
     * 先写同目录临时文件再重命名替换目标，失败时清理临时文件。
     *
     * @param string $target 待原子写入的目标文件路径，父目录应已存在。
     * @param string $bytes 需要完整写入的文件字节内容。
     * @return void 无返回值；短写或重命名失败抛出 RuntimeException。
     *
     * 内部调用示例（仅类内使用）：
     * @example self::write($target, $source);
     */
    private static function write(string $target, string $bytes): void
    {
        $temp = tempnam(dirname($target), '.grpc-');
        try {
            if (file_put_contents($temp, $bytes) !== strlen($bytes) || !rename($temp, $target)) {
                throw new \RuntimeException('Cannot write ' . $target);
            }
        } finally {
            if (is_file($temp)) {
                unlink($temp);
            }
        }
    }
}
